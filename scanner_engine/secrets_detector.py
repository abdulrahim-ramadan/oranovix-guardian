"""
Secrets Detection Scanner for Oranovix Guardian.

Detects hardcoded secrets, API keys, passwords, connection strings, private keys,
and JWT tokens across ALL file types regardless of programming language.

Architecture follows the existing BaseScanner pattern with ABC-based SecretPattern
classes for extensibility.

Version: 1.0.0
"""
from __future__ import annotations

import re
from abc import ABC, abstractmethod
from pathlib import Path
from typing import List

from .base import BaseScanner, FileMatcher, Issue, Language, ScanResult, Severity
from .categories import IssueCategory


# ---------------------------------------------------------------------------
# Abstract base for a single secret pattern
# ---------------------------------------------------------------------------

class SecretPattern(ABC):
    """Abstract base class for a single secret detection regex pattern.

    Each concrete subclass encapsulates one type of secret:
    its regex, human-readable type name, and severity level.
    """

    @property
    @abstractmethod
    def pattern(self) -> str:
        """Return the regex pattern string that matches this secret type."""

    @property
    @abstractmethod
    def secret_type(self) -> str:
        """Return a human-readable name for this secret type."""

    @property
    @abstractmethod
    def severity(self) -> Severity:
        """Return the severity level for exposure of this secret."""

    @property
    def rule_id(self) -> str:
        """Return the rule ID for issues generated by this pattern."""
        return "SEC-SCRT"


# ---------------------------------------------------------------------------
# Concrete pattern classes
# ---------------------------------------------------------------------------

class AWSKeyPattern(SecretPattern):
    """Detects hardcoded AWS Access Key IDs (AKIA...)."""

    @property
    def pattern(self) -> str:
        return r'(AKIA[0-9A-Z]{16})'

    @property
    def secret_type(self) -> str:
        return "AWS Access Key ID"

    @property
    def severity(self) -> Severity:
        return Severity.CRITICAL

    @property
    def rule_id(self) -> str:
        return "SEC-AWS01"


class OpenAIKeyPattern(SecretPattern):
    """Detects hardcoded OpenAI API keys (sk-...)."""

    @property
    def pattern(self) -> str:
        return r'(sk-[a-zA-Z0-9]{48})'

    @property
    def secret_type(self) -> str:
        return "OpenAI API Key"

    @property
    def severity(self) -> Severity:
        return Severity.CRITICAL

    @property
    def rule_id(self) -> str:
        return "SEC-OAI01"


class GitHubTokenPattern(SecretPattern):
    """Detects hardcoded GitHub Personal Access Tokens (ghp_...)."""

    @property
    def pattern(self) -> str:
        return r'(ghp_[a-zA-Z0-9]{36})'

    @property
    def secret_type(self) -> str:
        return "GitHub Personal Access Token"

    @property
    def severity(self) -> Severity:
        return Severity.CRITICAL

    @property
    def rule_id(self) -> str:
        return "SEC-GHP01"


class PasswordPattern(SecretPattern):
    """Detects passwords, passwd, or secret assigned as string literals."""

    @property
    def pattern(self) -> str:
        return r'(?i)(?:password|passwd|secret)\s*=\s*["\'][^"\']{4,}["\']'

    @property
    def secret_type(self) -> str:
        return "Password"

    @property
    def severity(self) -> Severity:
        return Severity.CRITICAL

    @property
    def rule_id(self) -> str:
        return "SEC-PWD01"


class ConnectionStringPattern(SecretPattern):
    """Detects database connection strings with embedded credentials."""

    @property
    def pattern(self) -> str:
        return r'(?:mongodb|postgresql|mysql)://[^:\s]+:[^@\s]+@'

    @property
    def secret_type(self) -> str:
        return "Database Connection String with Credentials"

    @property
    def severity(self) -> Severity:
        return Severity.CRITICAL

    @property
    def rule_id(self) -> str:
        return "SEC-CONN1"


class PrivateKeyPattern(SecretPattern):
    """Detects PEM-encoded RSA, EC, or DSA private key blocks."""

    @property
    def pattern(self) -> str:
        return r'-----BEGIN (?:RSA|EC|DSA) PRIVATE KEY-----'

    @property
    def secret_type(self) -> str:
        return "Private Key (PEM)"

    @property
    def severity(self) -> Severity:
        return Severity.CRITICAL

    @property
    def rule_id(self) -> str:
        return "SEC-PRVK1"


class JWTPattern(SecretPattern):
    """Detects hardcoded JWT tokens embedded in source code."""

    @property
    def pattern(self) -> str:
        return r'eyJ[a-zA-Z0-9_-]+\.eyJ[a-zA-Z0-9_-]+'

    @property
    def secret_type(self) -> str:
        return "JWT Token"

    @property
    def severity(self) -> Severity:
        return Severity.HIGH

    @property
    def rule_id(self) -> str:
        return "SEC-JWT01"


# ---------------------------------------------------------------------------
# File extensions to scan (all common text-based source formats)
# ---------------------------------------------------------------------------

_ALL_TEXT_EXTENSIONS: List[str] = [
    ".py", ".pyw", ".js", ".ts", ".jsx", ".tsx", ".mjs",
    ".php", ".java", ".cs", ".rb", ".go", ".rs", ".swift",
    ".env", ".cfg", ".conf", ".config", ".ini",
    ".yaml", ".yml", ".json", ".xml", ".toml",
    ".sh", ".bash", ".zsh", ".ps1", ".bat", ".cmd",
    ".tf", ".hcl", ".txt",
    ".sql", ".graphql", ".vue", ".svelte", ".dart",
    ".properties", ".gradle", ".pom",
]

# Config files that carry credentials but have no usable extension.
_CONFIG_FILE_NAMES: List[str] = [
    "Dockerfile", "docker-compose", "compose",
    ".htpasswd", ".npmrc", ".pypirc",
]


# ---------------------------------------------------------------------------
# SecretsDetector scanner
# ---------------------------------------------------------------------------

class SecretsDetector(BaseScanner):
    """Scanner that detects hardcoded secrets across ALL file types.

    Runs every registered SecretPattern against each text file in the scan
    target, regardless of programming language.  Results are intended to be
    merged with language-specific scanner output.

    All seven built-in patterns are applied: AWSKeyPattern, OpenAIKeyPattern,
    GitHubTokenPattern, PasswordPattern, ConnectionStringPattern,
    PrivateKeyPattern, and JWTPattern.
    """

    SUPPORTED_EXTENSIONS: List[str] = _ALL_TEXT_EXTENSIONS
    SUPPORTED_FILE_NAMES: List[str] = _CONFIG_FILE_NAMES

    _PATTERNS: List[SecretPattern] = [
        AWSKeyPattern(),
        OpenAIKeyPattern(),
        GitHubTokenPattern(),
        PasswordPattern(),
        ConnectionStringPattern(),
        PrivateKeyPattern(),
        JWTPattern(),
    ]

    def __init__(self) -> None:
        super().__init__(
            name="Secrets Detector",
            supported_language=Language.UNKNOWN,
        )
        # Pre-compile all patterns once for performance across many files
        self._compiled: List[tuple] = [
            (p, re.compile(p.pattern, re.MULTILINE))
            for p in self._PATTERNS
        ]

    def supports(self, file_path: str) -> bool:
        """Return True for recognised text extensions, dotfiles and config names."""
        matcher = FileMatcher(self.SUPPORTED_EXTENSIONS, self.SUPPORTED_FILE_NAMES)
        return matcher.matches(Path(file_path).name)

    def _do_scan(self, target: str, result: ScanResult) -> ScanResult:
        """Scan all text files under target for hardcoded secrets.

        Args:
            target: File or directory path to scan.
            result: Pre-initialised ScanResult to populate.

        Returns:
            The populated ScanResult with secrets issues added.
        """
        files = self.collect_files(
            target, self.SUPPORTED_EXTENSIONS, self.SUPPORTED_FILE_NAMES
        )
        result.files_scanned = len(files)

        for file_path in files:
            result.issues.extend(self._scan_file(file_path))

        return result

    def _scan_file(self, file_path: str) -> List[Issue]:
        """Apply all secret patterns to a single file.

        Args:
            file_path: Absolute path to the file to scan.

        Returns:
            List of Issue objects for every match found; empty if none.
        """
        issues: List[Issue] = []
        try:
            source = Path(file_path).read_text(encoding="utf-8", errors="ignore")
        except OSError:
            return issues

        lines = source.splitlines()

        for pattern_obj, compiled in self._compiled:
            for match in compiled.finditer(source):
                line_num = source[: match.start()].count("\n") + 1
                snippet = lines[line_num - 1].strip() if line_num <= len(lines) else ""

                # Mask the matched value to avoid displaying raw secrets in the UI
                matched_value = match.group(0)
                if len(matched_value) > 12:
                    display_value = matched_value[:6] + "..." + matched_value[-4:]
                else:
                    display_value = "***"

                issues.append(Issue(
                    rule_id=pattern_obj.rule_id,
                    title=f"Hardcoded {pattern_obj.secret_type}",
                    description=(
                        f"Detected a hardcoded {pattern_obj.secret_type} "
                        f"({display_value}) in source code. "
                        "Secrets committed to source control can be extracted from "
                        "git history, compiled binaries, or process memory."
                    ),
                    severity=pattern_obj.severity,
                    file_path=file_path,
                    line_number=line_num,
                    code_snippet=snippet,
                    recommendation=(
                        f"Remove the hardcoded {pattern_obj.secret_type} and store it "
                        "in an environment variable or a secrets manager "
                        "(AWS Secrets Manager, HashiCorp Vault, python-decouple). "
                        "Rotate the credential immediately if it was ever committed."
                    ),
                    cwe="https://cwe.mitre.org/data/definitions/798.html",
                    confidence="HIGH",
                    category=IssueCategory.SECRET,
                ))

        return issues
